import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourceDir = path.join(root, "public", "images", "agenda", "activities");
const outputFile = path.join(root, "data", "agenda-images.generated.ts");
const allowed = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walk(absolute));
    } else if (entry.isFile() && allowed.has(path.extname(entry.name).toLowerCase())) {
      files.push(absolute);
    }
  }

  return files;
}

function labelFromFile(relative) {
  return path.basename(relative, path.extname(relative))
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

await mkdir(sourceDir, { recursive: true });

const files = (await walk(sourceDir))
  .map((absolute) => path.relative(sourceDir, absolute).split(path.sep).join("/"))
  .sort((a, b) => a.localeCompare(b, "nl"));

const images = files.map((relative) => ({
  path: `/images/agenda/activities/${relative}`,
  fileName: path.basename(relative),
  label: labelFromFile(relative),
}));

const source = `// AUTO-GENERATED by scripts/generate-agenda-image-manifest.mjs
// Add images to public/images/agenda/activities/ and run dev/build.

export type AgendaActivityImage = {
  path: string;
  fileName: string;
  label: string;
};

export const agendaActivityImages: AgendaActivityImage[] = ${JSON.stringify(images, null, 2)};
`;

await writeFile(outputFile, source, "utf8");
console.log(`Agenda image manifest: ${images.length} image(s)`);
