import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const activitiesDir = path.join(root, "public", "images", "agenda", "activities");
const containerDir = path.join(activitiesDir, "container-images");
const detailDir = path.join(activitiesDir, "detail-images");
const outputFile = path.join(root, "data", "agenda-images.generated.ts");
const allowed = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walk(absolute));
    } else if (entry.isFile() && allowed.has(path.extname(entry.name).toLowerCase())) {
      files.push(absolute);
    }
  }

  return files;
}

function labelFromFile(relative) {
  return path.basename(relative, path.extname(relative))
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

async function buildImages(dir, publicPrefix) {
  const files = (await walk(dir))
    .map((absolute) => path.relative(dir, absolute).split(path.sep).join("/"))
    .sort((a, b) => a.localeCompare(b, "nl"));

  return files.map((relative) => ({
    path: `${publicPrefix}/${relative}`,
    fileName: path.basename(relative),
    label: labelFromFile(relative),
  }));
}

await Promise.all([
  mkdir(containerDir, { recursive: true }),
  mkdir(detailDir, { recursive: true }),
]);

const [containerImages, detailImages] = await Promise.all([
  buildImages(containerDir, "/images/agenda/activities/container-images"),
  buildImages(detailDir, "/images/agenda/activities/detail-images"),
]);

const source = `// AUTO-GENERATED by scripts/generate-agenda-image-manifest.mjs
// Add images to the container-images/detail-images folders and run dev/build.

export type AgendaActivityImage = {
  path: string;
  fileName: string;
  label: string;
};

export const agendaContainerImages: AgendaActivityImage[] = ${JSON.stringify(containerImages, null, 2)};

export const agendaDetailImages: AgendaActivityImage[] = ${JSON.stringify(detailImages, null, 2)};
`;

await writeFile(outputFile, source, "utf8");
console.log(`Agenda image manifest: ${containerImages.length} container image(s), ${detailImages.length} detail image(s)`);
